void gfx_init(uint8_t *addr, uint32_t width, uint32_t height,
              uint32_t pitch, uint8_t bpp) {
    fb_addr   = addr;
    fb_width  = width;
    fb_height = height;
    fb_pitch  = pitch;
    fb_bpp    = bpp;
    gfx_ready = (addr && width && height && pitch && (bpp == 32 || bpp == 24));
}

static inline void put32(int x, int y, uint32_t c) {
    if ((unsigned)x >= fb_width || (unsigned)y >= fb_height) return;
    uint8_t *p = fb_addr + y * fb_pitch + x * (fb_bpp / 8);
    if (fb_bpp == 32) {
        *(uint32_t *)p = c;
    } else if (fb_bpp == 24) {
        p[0] = c & 0xFF;
        p[1] = (c >> 8) & 0xFF;
        p[2] = (c >> 16) & 0xFF;
    }
}

void gfx_putpixel(int x, int y, color_t c) {
    put32(x, y, c);
}

color_t gfx_getpixel(int x, int y) {
    if ((unsigned)x >= fb_width || (unsigned)y >= fb_height) return 0;
    uint8_t *p = fb_addr + y * fb_pitch + x * (fb_bpp / 8);
    if (fb_bpp == 32) return *(uint32_t *)p;
    if (fb_bpp == 24) return p[0] | (p[1] << 8) | (p[2] << 16);
    return 0;
}

void gfx_clear(color_t c) {
    if (!gfx_ready) return;
    for (uint32_t y = 0; y < fb_height; y++) {
        uint8_t *row = fb_addr + y * fb_pitch;
        if (fb_bpp == 32) {
            uint32_t *p = (uint32_t *)row;
            for (uint32_t x = 0; x < fb_width; x++) p[x] = c;
        } else {
            for (uint32_t x = 0; x < fb_width; x++) {
                row[x*3+0] = c & 0xFF;
                row[x*3+1] = (c >> 8) & 0xFF;
                row[x*3+2] = (c >> 16) & 0xFF;
            }
        }
    }
}

void gfx_fill_rect(int x, int y, int w, int h, color_t c) {
    if (w <= 0 || h <= 0) return;
    for (int dy = 0; dy < h; dy++)
        for (int dx = 0; dx < w; dx++)
            put32(x + dx, y + dy, c);
}

void gfx_hline(int x, int y, int len, color_t c) {
    for (int i = 0; i < len; i++) put32(x + i, y, c);
}

void gfx_vline(int x, int y, int len, color_t c) {
    for (int i = 0; i < len; i++) put32(x, y + i, c);
}

